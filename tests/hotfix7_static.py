from pathlib import Path
import re, sys
root=Path(__file__).resolve().parents[1]
imp=(root/'import.lua').read_text()
mt=(root/'server/migration_transport.lua').read_text()
mig=(root/'server/migrations.lua').read_text()
fx=(root/'fxmanifest.lua').read_text()
const=(root/'shared/constants.lua').read_text()
checks=[]
def c(n,v): checks.append((n,bool(v)))
c('version hotfix.7', "version '1.0.0-rc.1.hotfix.7'" in fx and "VERSION = '1.0.0-rc.1.hotfix.7'" in const)
c('build consistent', all('mvp_rc1_migration_proxy_4a91e7d2' in x for x in [fx,const,imp]))
c('migration transport loaded', "'server/migration_transport.lua'" in fx)
c('request is server-local event', "AddEventHandler(REQUEST_EVENT" in mt and 'RegisterNetEvent' not in re.sub(r'--[^\n]*','',mt))
c('real invoking resource required', 'GetInvokingResource' in mt and 'claimedOwner ~= invoking' in mt)
c('Core-owned coroutine', 'CreateThread(function()' in mt and 'Migrations.Run(invoking)' in mt)
c('no pcall/xpcall around Core transport run', 'pcall(' not in re.sub(r'--[^\n]*','',mt) and 'xpcall(' not in re.sub(r'--[^\n]*','',mt))
c('consumer overrides public migration Run', 'publicFacade.Migrations.Run = runMigrationsViaLocalEventProxy' in imp)
c('consumer request uses TriggerEvent', 'TriggerEvent(MIGRATION_RUN_REQUEST_EVENT' in imp)
c('consumer waits only local promise', 'local envelope = Citizen.Await(p)' in imp)
c('transport timeout exists', 'MIGRATION_RUN_TIMEOUT_MS = 30000' in imp and 'SetTimeout(MIGRATION_RUN_TIMEOUT_MS' in imp)
c('result uses dense transport envelope', 'Transport.Pack(ok, err)' in mt and 'return unpackEnvelope(envelope)' in imp)
c('checksum guard preserved', 'MIGRATION_CHECKSUM_MISMATCH' in mig)
c('duplicate run guard preserved', 'if running[resource] then' in mig)
c('cleanupPending preserved', 'cleanupPending[resource]' in mig)
c('applied SQL unchanged', 'SELECT `migration`, `checksum` FROM `nexm_migrations` WHERE `resource` = ?' in mig)
c('bookkeeping SQL unchanged', 'INSERT INTO `nexm_migrations` (`resource`, `migration`, `checksum`) VALUES (?, ?, ?)' in mig)
for n,v in checks: print(('[PASS] ' if v else '[FAIL] ')+n)
fail=sum(not v for _,v in checks)
print(f'RESULT tests={len(checks)} pass={len(checks)-fail} fail={fail}')
sys.exit(1 if fail else 0)
